export function stationLabel(name: string) {
  return name.endsWith("역") ? name : `${name}역`;
}

export function isStationName(name: string) {
  const compact = name.replace(/\s+/g, "");
  return compact.includes("역") || compact.includes("지하철");
}

export function searchLocalStations(query: string, limit = 8) {
  const needle = query.trim().replace(/역$/, "");
  if (!needle) return [];
  return STATIONS.filter((station) => station.name.includes(needle) && hasSubwayStation(station.name)).slice(
    0,
    limit,
  );
}

const POPULAR_STATIONS = [
  "강남",
  "홍대입구",
  "잠실",
  "서울역",
  "신촌",
  "여의도",
  "건대입구",
  "왕십리",
  "사당",
  "고속터미널",
  "월곡",
  "노원",
];

export function suggestStations(query: string, limit = 12): Station[] {
  const needle = query.trim().replace(/\s+/g, "").replace(/역$/, "");
  if (!needle) {
    return POPULAR_STATIONS.map((name) => STATIONS.find((station) => station.name === name)).filter(
      (station): station is Station => Boolean(station),
    );
  }

  const starts = STATIONS.filter(
    (station) =>
      hasSubwayStation(station.name) &&
      (station.name.startsWith(needle) || stationLabel(station.name).startsWith(query.trim())),
  );
  const rest = STATIONS.filter(
    (station) =>
      hasSubwayStation(station.name) &&
      station.name.includes(needle) &&
      !starts.some((item) => item.name === station.name),
  );
  return [...starts, ...rest].slice(0, limit);
}

export function stationsWithin(center: LatLng, radiusKm: number) {
  return STATIONS.filter((station) => haversineKm(center, station) <= radiusKm);
}

export function nearestStation(point: LatLng) {
  return STATIONS.reduce((best, station) => {
    return haversineKm(point, station) < haversineKm(point, best) ? station : best;
  });
}
